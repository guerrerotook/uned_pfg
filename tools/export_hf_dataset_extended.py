"""Export the **synthetic** CIMA section-4.8 NER corpus for Hugging Face.

Companion to :mod:`tools.export_hf_dataset` (which publishes the *real*
corpus as ``CIMA-4.8-ADR-NER``). This script publishes the Variante B
corpus generated by ``run_synth_dataset.py``: 98 fictional section-4.8
documents (49 drugs x 2 variants) written by an LLM from the canonical
(reaction, frequency, system) tuples of real CIMA drugs.

Sources:

- ``data/medicamentos_synth/txt/{codigo}_v{n}.txt``   → synthetic text
- ``data/medicamentos_synth/entities/*.json``         → char-offset spans
- ``data/splits/full_annotations_synth.csv``          → mention table
- ``data/splits/{train,test}_synth.csv``              → drug-level splits

Everything is written under ``huggingface/CIMA-4.8-ADR-NER-EXTENDED/``:

- ``data/{config}/{split}.parquet``  → 5 BIO configs, same schema and
  builder as the real dataset, so a consumer can swap ``repo_id``.
- ``data/documents/{split}.parquet`` → one row per document with the full
  text and the entity spans (``start``/``end`` are character offsets into
  ``text``), for consumers that want to re-tokenise.
- ``conll/{config}/{split}.conll``   → plain ``token\\tlabel`` BIO files.
- ``txt/``                           → verbatim copy of the 98 documents.
- ``annotations/``                   → verbatim copy of the three CSVs.
- ``stats/{config}.json`` + ``stats/summary.json``.

Run from the repo root::

    python tools/export_hf_dataset_extended.py

The raw LLM responses (``data/medicamentos_synth/raw_responses/``) are
**not** published: they embed the generation prompts.
"""

from __future__ import annotations

import json
import os
import shutil
import sys
from collections import Counter

import pandas as pd
from datasets import Dataset, Features, Value

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_TOOLS_DIR = os.path.join(_REPO_ROOT, "tools")
for _p in (_REPO_ROOT, _TOOLS_DIR):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from src.conll_ner_builder import ConllBuilder, _normalise  # noqa: E402

# Reuse the real exporter's helpers verbatim so both datasets are produced
# by the same code path (only the input corpus and destination differ).
from export_hf_dataset import (  # noqa: E402
    TAG_COMBINATIONS,
    _build_examples,
    _config_name,
    _summary,
    _to_hf_dataset,
    _write_conll,
)

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
SYNTH_DIR = os.path.join(_REPO_ROOT, "data/medicamentos_synth")
SYNTH_TXT_DIR = os.path.join(SYNTH_DIR, "txt")
SYNTH_ENTITIES_DIR = os.path.join(SYNTH_DIR, "entities")

TRAIN_CSV = os.path.join(_REPO_ROOT, "data/splits/train_synth.csv")
TEST_CSV = os.path.join(_REPO_ROOT, "data/splits/test_synth.csv")
FULL_ANNOTATIONS_CSV = os.path.join(_REPO_ROOT, "data/splits/full_annotations_synth.csv")

OUTPUT_DIR = os.path.join(_REPO_ROOT, "huggingface/CIMA-4.8-ADR-NER-EXTENDED")

ENTITY_TYPES = ["REACT", "ACTIVE", "FREQ", "SYS"]

DOCUMENT_FEATURES = Features(
    {
        "codigo": Value("string"),
        "orig_codigo": Value("string"),
        "variante": Value("int32"),
        "medicamento": Value("string"),
        "text": Value("string"),
        "discard_ratio": Value("float32"),
        # List-of-structs (not Sequence-of-Features, which would transpose
        # each row into a struct-of-lists).
        "entities": [
            {
                "type": Value("string"),
                "canonical": Value("string"),
                "surface": Value("string"),
                "start": Value("int32"),
                "end": Value("int32"),
            }
        ],
    }
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def _load_synth_csv(path: str) -> pd.DataFrame:
    """Read a synthetic split CSV keeping both código columns as strings."""
    df = pd.read_csv(path, dtype={"CODIGO": str, "ORIG_CODIGO": str})
    for col in ("CODIGO", "ORIG_CODIGO"):
        df[col] = df[col].astype(str).str.strip()
    return df


def _codigo_aliases(codigos: set[str]) -> dict[str, str]:
    """Map each CSV CODIGO to the basename actually present in the corpus.

    The generator dropped leading zeros when naming a few documents (the CSVs
    say ``07387014_v1`` but the corpus holds ``7387014_v1``). Without this
    remap ``ConllBuilder`` finds no .txt and silently drops those documents.
    """
    aliases: dict[str, str] = {}
    for codigo in codigos:
        if os.path.exists(os.path.join(SYNTH_TXT_DIR, f"{codigo}.txt")):
            continue
        stripped = codigo.lstrip("0")
        if stripped != codigo and os.path.exists(
            os.path.join(SYNTH_TXT_DIR, f"{stripped}.txt")
        ):
            aliases[codigo] = stripped
    return aliases


def _apply_aliases(df: pd.DataFrame, aliases: dict[str, str]) -> pd.DataFrame:
    df = df.copy()
    df["CODIGO"] = df["CODIGO"].map(lambda c: aliases.get(c, c))
    return df


def _drop_leaked_test_drugs(
    train_df: pd.DataFrame, test_df: pd.DataFrame
) -> tuple[set[str], list[str]]:
    """Return the test CODIGOs to publish plus the drugs dropped from test.

    A synthetic CODIGO is variant-suffixed (``{ORIG_CODIGO}_v{n}``), so two
    variants of the same drug landing on opposite sides of the split would
    leak. Any ORIG_CODIGO present in both splits is removed from **test**
    (train keeps it), which guarantees the no-leakage-by-drug property.
    """
    leaked = sorted(set(train_df["ORIG_CODIGO"]) & set(test_df["ORIG_CODIGO"]))
    kept = set(test_df.loc[~test_df["ORIG_CODIGO"].isin(leaked), "CODIGO"])
    return kept, leaked


def _load_documents(codigos: set[str], annotations: pd.DataFrame) -> list[dict]:
    """Build the ``documents`` rows for ``codigos`` from ``entities/*.json``."""
    orig_by_codigo = (
        annotations.drop_duplicates("CODIGO").set_index("CODIGO")["ORIG_CODIGO"].to_dict()
    )

    rows: list[dict] = []
    for codigo in sorted(codigos):
        ent_path = os.path.join(SYNTH_ENTITIES_DIR, f"{codigo}.json")
        txt_path = os.path.join(SYNTH_TXT_DIR, f"{codigo}.txt")
        if not (os.path.exists(ent_path) and os.path.exists(txt_path)):
            raise FileNotFoundError(
                f"Synthetic document '{codigo}' is referenced by the splits but "
                f"missing on disk ({ent_path} / {txt_path})."
            )
        with open(ent_path, "r", encoding="utf-8") as f:
            payload = json.load(f)
        with open(txt_path, "r", encoding="utf-8") as f:
            text = f.read()

        entities = [
            {
                "type": str(ent["type"]),
                "canonical": str(ent.get("canonical") or ent["surface"]),
                "surface": str(ent["surface"]),
                "start": int(ent["start"]),
                "end": int(ent["end"]),
            }
            for ent in payload.get("entities", [])
            if str(ent.get("type", "")).upper() in ENTITY_TYPES
        ]
        # The generator located every span with accent/case-insensitive
        # matching, so text[start:end] may differ from `surface` in casing.
        for ent in entities:
            span = text[ent["start"] : ent["end"]]
            if _normalise(span) != _normalise(ent["surface"]):
                raise ValueError(
                    f"Offset mismatch in {codigo}: text[{ent['start']}:{ent['end']}] "
                    f"= {span!r} != {ent['surface']!r}"
                )

        rows.append(
            {
                "codigo": codigo,
                "orig_codigo": str(
                    orig_by_codigo.get(codigo) or payload.get("codigo") or ""
                ).strip(),
                "variante": int(payload.get("variante", 0)),
                "medicamento": str(payload.get("medicamento") or ""),
                "text": text,
                "discard_ratio": float(payload.get("discard_ratio", 0.0)),
                "entities": entities,
            }
        )
    return rows


def _documents_summary(rows: list[dict]) -> dict:
    entity_counts: Counter[str] = Counter()
    for row in rows:
        entity_counts.update(ent["type"] for ent in row["entities"])
    chars = [len(row["text"]) for row in rows]
    words = [len(row["text"].split()) for row in rows]
    return {
        "documents": len(rows),
        "drugs": len({row["orig_codigo"] for row in rows}),
        "entities": sum(entity_counts.values()),
        "entity_counts": dict(entity_counts),
        "mean_chars": round(sum(chars) / len(chars), 1) if chars else 0.0,
        "mean_words": round(sum(words) / len(words), 1) if words else 0.0,
    }


def _copy_tree(src_dir: str, dst_dir: str, suffix: str) -> int:
    os.makedirs(dst_dir, exist_ok=True)
    names = sorted(n for n in os.listdir(src_dir) if n.endswith(suffix))
    for name in names:
        shutil.copy2(os.path.join(src_dir, name), os.path.join(dst_dir, name))
    return len(names)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def export_all() -> None:
    if not os.path.isdir(SYNTH_TXT_DIR):
        raise FileNotFoundError(
            f"Synthetic text directory not found: {SYNTH_TXT_DIR}. "
            "Run `python run_synth_dataset.py` first."
        )

    train_df = _load_synth_csv(TRAIN_CSV)
    test_df = _load_synth_csv(TEST_CSV)
    full_df = _load_synth_csv(FULL_ANNOTATIONS_CSV)

    aliases = _codigo_aliases(set(full_df["CODIGO"]))
    if aliases:
        print(
            f"{len(aliases)} CODIGO(s) del CSV no coinciden con el nombre de fichero "
            f"y se normalizan: {aliases}"
        )
    train_df = _apply_aliases(train_df, aliases)
    test_df = _apply_aliases(test_df, aliases)
    full_df = _apply_aliases(full_df, aliases)

    train_codigos = set(train_df["CODIGO"])
    test_codigos, leaked_drugs = _drop_leaked_test_drugs(train_df, test_df)

    if leaked_drugs:
        print(
            f"{len(leaked_drugs)} fármaco(s) aparecían en train y test: "
            f"{leaked_drugs}. Sus variantes se excluyen del split de test."
        )
    else:
        print("Sin fuga entre splits: ningún ORIG_CODIGO aparece en train y test.")

    print(
        f"Exportando dataset NER sintético para Hugging Face\n"
        f"   train_synth.csv: {len(train_df):,} filas, {len(train_codigos)} documentos, "
        f"{train_df['ORIG_CODIGO'].nunique()} fármacos\n"
        f"   test_synth.csv:  {len(test_df):,} filas, {len(test_codigos)} documentos, "
        f"{test_df['ORIG_CODIGO'].nunique()} fármacos\n"
        f"   full_annotations_synth.csv: {len(full_df):,} filas\n"
        f"   destino: {OUTPUT_DIR}\n"
    )

    stats_dir = os.path.join(OUTPUT_DIR, "stats")
    os.makedirs(stats_dir, exist_ok=True)
    global_summary: dict[str, dict] = {}

    # --- BIO configs -------------------------------------------------------
    for tags in TAG_COMBINATIONS:
        cfg = _config_name(tags)
        print(f"\n=== Config: {cfg} (tags={tags}) ===")

        builder = ConllBuilder(txt_dir=SYNTH_TXT_DIR, entity_types=tags)
        label_names = list(builder.label_to_id.keys())
        id_to_label = builder.id_to_label

        train_examples = _build_examples(builder, train_codigos, full_df)
        train_missing = list(builder.missing_txt_files)
        train_no_tags = list(builder.docs_with_no_tags)
        test_examples = _build_examples(builder, test_codigos, full_df)
        test_missing = list(builder.missing_txt_files)
        test_no_tags = list(builder.docs_with_no_tags)

        train_summary = _summary(train_examples, id_to_label)
        test_summary = _summary(test_examples, id_to_label)
        train_summary.update(missing_txt_files=train_missing, docs_with_no_tags=train_no_tags)
        test_summary.update(missing_txt_files=test_missing, docs_with_no_tags=test_no_tags)

        if train_missing or test_missing:
            raise FileNotFoundError(
                f"Config '{cfg}': documentos sin .txt en el corpus sintético — "
                f"train={train_missing}, test={test_missing}"
            )

        parquet_dir = os.path.join(OUTPUT_DIR, "data", cfg)
        conll_dir = os.path.join(OUTPUT_DIR, "conll", cfg)
        os.makedirs(parquet_dir, exist_ok=True)
        os.makedirs(conll_dir, exist_ok=True)

        train_ds = _to_hf_dataset(train_examples, label_names)
        test_ds = _to_hf_dataset(test_examples, label_names)
        train_ds.to_parquet(os.path.join(parquet_dir, "train.parquet"))
        test_ds.to_parquet(os.path.join(parquet_dir, "test.parquet"))

        _write_conll(train_examples, os.path.join(conll_dir, "train.conll"), id_to_label)
        _write_conll(test_examples, os.path.join(conll_dir, "test.conll"), id_to_label)

        with open(os.path.join(stats_dir, f"{cfg}.json"), "w", encoding="utf-8") as f:
            json.dump(
                {
                    "config": cfg,
                    "entity_types": tags,
                    "labels": label_names,
                    "train": train_summary,
                    "test": test_summary,
                },
                f,
                ensure_ascii=False,
                indent=2,
            )

        print(
            f"  train: {train_summary['documents']} docs / "
            f"{train_summary['sentences']:,} sentences / "
            f"{train_summary['tokens']:,} tokens"
        )
        print(
            f"  test:  {test_summary['documents']} docs / "
            f"{test_summary['sentences']:,} sentences / "
            f"{test_summary['tokens']:,} tokens"
        )

        global_summary[cfg] = {
            "labels": label_names,
            "train_sentences": train_summary["sentences"],
            "test_sentences": test_summary["sentences"],
            "train_tokens": train_summary["tokens"],
            "test_tokens": test_summary["tokens"],
        }

    # --- documents config --------------------------------------------------
    print("\n=== Config: documents (texto completo + spans) ===")
    doc_dir = os.path.join(OUTPUT_DIR, "data", "documents")
    os.makedirs(doc_dir, exist_ok=True)

    train_docs = _load_documents(train_codigos, full_df)
    test_docs = _load_documents(test_codigos, full_df)
    Dataset.from_list(train_docs, features=DOCUMENT_FEATURES).to_parquet(
        os.path.join(doc_dir, "train.parquet")
    )
    Dataset.from_list(test_docs, features=DOCUMENT_FEATURES).to_parquet(
        os.path.join(doc_dir, "test.parquet")
    )

    doc_train_summary = _documents_summary(train_docs)
    doc_test_summary = _documents_summary(test_docs)
    with open(os.path.join(stats_dir, "documents.json"), "w", encoding="utf-8") as f:
        json.dump(
            {
                "config": "documents",
                "entity_types": ENTITY_TYPES,
                "train": doc_train_summary,
                "test": doc_test_summary,
            },
            f,
            ensure_ascii=False,
            indent=2,
        )
    print(
        f"  train: {doc_train_summary['documents']} docs / "
        f"{doc_train_summary['entities']:,} entidades"
    )
    print(
        f"  test:  {doc_test_summary['documents']} docs / "
        f"{doc_test_summary['entities']:,} entidades"
    )

    global_summary["documents"] = {
        "train_documents": doc_train_summary["documents"],
        "test_documents": doc_test_summary["documents"],
        "train_entities": doc_train_summary["entities"],
        "test_entities": doc_test_summary["entities"],
    }

    # --- raw copies --------------------------------------------------------
    n_txt = _copy_tree(SYNTH_TXT_DIR, os.path.join(OUTPUT_DIR, "txt"), ".txt")
    ann_dir = os.path.join(OUTPUT_DIR, "annotations")
    os.makedirs(ann_dir, exist_ok=True)
    # Written from the aliased frames so every CODIGO resolves to a txt/ file.
    for path, df in (
        (FULL_ANNOTATIONS_CSV, full_df),
        (TRAIN_CSV, train_df),
        (TEST_CSV, test_df),
    ):
        df.to_csv(os.path.join(ann_dir, os.path.basename(path)), index=False)
    print(f"\nCopiados {n_txt} .txt y 3 CSV de anotaciones")

    # --- global summary ----------------------------------------------------
    summary_path = os.path.join(stats_dir, "summary.json")
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(
            {
                "corpus": "synthetic",
                "source": "data/medicamentos_synth",
                "documents": len(train_codigos) + len(test_codigos),
                "drugs": full_df["ORIG_CODIGO"].nunique(),
                "excluded_from_test": leaked_drugs,
                "codigo_normalisation": aliases,
                "configs": global_summary,
            },
            f,
            ensure_ascii=False,
            indent=2,
        )
    print(f"\nExportación completa. Resumen global: {summary_path}")


if __name__ == "__main__":
    export_all()
